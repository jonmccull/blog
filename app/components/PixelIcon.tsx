export type PixelIconName = keyof typeof grids

// One path of 1-cell-high runs per icon, built once
const paths = Object.fromEntries(
  Object.entries(grids).map(([name, rows]) => [
    name,
    rows
      .flatMap((row, y) =>
        [...row.matchAll(/#+/g)].map((m) => `M${m.index} ${y}h${m[0].length}v1h-${m[0].length}z`)
      )
      .join(''),
  ])
) as Record<PixelIconName, string>

export function PixelIcon({ name }: { name: PixelIconName }) {
  return (
    <svg
      className="pixel-icon"
      viewBox="0 0 16 16"
      width={16}
      height={16}
      shapeRendering="crispEdges"
      fill="currentColor"
      aria-hidden="true"
      focusable="false"
    >
      <path d={paths[name]} />
    </svg>
  )
}
